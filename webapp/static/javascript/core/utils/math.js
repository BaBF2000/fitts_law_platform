/**
 * Clamp a numeric value to a closed interval.
 *
 * Args:
 *   v: Value to clamp.
 *   a: Lower bound.
 *   b: Upper bound.
 *
 * Returns:
 *   v limited to the interval [a, b].
 *
 * Side effects:
 *   None.
 *
 * Important:
 *   This helper assumes that a <= b.
 */
export function clamp(v, a, b) {
  return Math.max(a, Math.min(b, v));
}

/**
 * Sample a pseudo-random number in the interval [0, 1).
 *
 * Returns:
 *   Number generated by Math.random().
 *
 * Side effects:
 *   Uses the browser's pseudo-random number generator.
 *
 * Notes:
 *   This function is not seeded, so results are not deterministic between runs.
 */
export function uniform01() {
  return Math.random();
}